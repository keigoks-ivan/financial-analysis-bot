ORDER_LINES: list = []     # live：本輪每個要調整的腿「占指數部 %」變化（水位 ÷ 2），給提醒信「怎麼下單」用


def detect_changes(prev: dict, sigs: dict, skip_legs=(), leg_dates: dict | None = None) -> list:
    """可行動變化＝任一腿今日目標與現持（執行層 executed_pct）差 ≥ 20pp（EXEC_BAND，
    與回測 A2 執行層 band_exec_replay 用同一個門檻）。閘門翻轉本身不是獨立觸發條件——
    若翻轉後的目標仍落在 20pp 門檻內，A2 不會調整部位，通知也不該提示調整；閘門翻轉
    只在同時達到 20pp 門檻時才隨通知文字一併標註（見 LOGIC_AUDIT.md 一之1：先前
    `gate_flip or drift` 會讓通知繞過 A2 門檻，唯一受影響的是「閘門開啟、但波動高導致
    目標很小」的情境——回測 A2 不動，通知卻可能叫使用者買到 20%；出場情境 target=0，
    動幅必達 20pp，不受影響，故修正後只會抑制小額再進場，不會抑制出場）。held is None
    （首次執行、無前一次 executed_pct 紀錄，無法比較門檻）時仍視為需要通知。改為與現持比
    （非與前一日目標比），才不會漏掉緩慢累積的漂移；alert 顯示取整後的建議動作
    （現持 → min(round(目標/10)×10, 50×cap)）。訊息標市場前綴（美股／台股）。
    2026-11-02 起實單減碼門檻 10pp（exec_down_band_for，依 leg_dates 的資料日判斷），加碼仍 20pp。"""
    ORDER_LINES.clear()
    if not prev or "tickers" not in prev:
        return []
    out = []
    for t in ALL_TICKERS:
        if t in skip_legs:        # 該市場資料延遲（見 tw_leg_delays）：不據舊價產生換倉指令
            continue
        pt = prev["tickers"].get(t)
        if not pt:
            continue
        gate_flip = bool(pt.get("gate")) != bool(sigs[t]["gate"])
        target = round(sigs[t]["final"] * 100, 1)
        held = pt.get("executed_pct")
        clamp = EXEC_CLAMP_NEW if sigs[t].get("rule") == NEW_RULE_TAG else EXEC_CLAMP
        # A2 一致性修正（LOGIC_AUDIT.md 一之1）：可行動事件只用 20pp 門檻判定，
        # 不再讓 gate_flip 單獨觸發——否則通知會在 A2 實際不動的情況下要求調整部位。
        # 2026-10-19 規則切換：現持高於新上限（例如 2330 持 60、上限 50）也算可行動，
        # 與 band_exec_replay 的「先拉回上限」同一式（next_exec）。
        if held is None:
            drift, new_exec = True, min(round(target / EXEC_GRID) * EXEC_GRID, clamp)
        else:
            down = exec_down_band_for(sigs[t], leg_dates[t]) if leg_dates else EXEC_BAND
            new_exec = next_exec(held, target, clamp, down)
            drift = new_exec != held
        if drift:
            parts = []
            if gate_flip:
                parts.append("閘門 " + ("出場→在場" if sigs[t]["gate"] else "在場→出場"))
            if PROFILE == "live":
                # 顯示換算：水位＝組合 pp × 2；占指數部＝水位 ÷ 2＝組合 pp（兩檔各占指數部一半）
                arrow = (f"水位 {lvl(held):.0f}% → {lvl(new_exec):.0f}%（目標 {lvl(target):.0f}%）"
                         if held is not None else f"水位 → {lvl(new_exec):.0f}%（目標 {lvl(target):.0f}%）")
                if held is not None and held > clamp:
                    arrow += f"（規則切換：不借錢版單檔上限水位 {lvl(clamp):.0f}%，先拉回上限）"
                ORDER_LINES.append(
                    f"{TICKER_MARKET[t]} {t} 占指數部 {held:.0f}% → {new_exec:.0f}%" if held is not None
                    else f"{TICKER_MARKET[t]} {t} 占指數部 → {new_exec:.0f}%")
            else:
                arrow = (f"最終權重 {held:.0f}% → {new_exec:.0f}%"
                         if held is not None else f"最終權重 → {new_exec:.0f}%")
                if held is not None and held > clamp:
                    arrow += f"（規則切換：不借錢版單腿上限 {clamp:.0f}%，先拉回上限）"
            out.append(f"<b>{TICKER_MARKET[t]} {t}</b>：{'、'.join(parts) + ' → ' if parts else ''}{arrow}")
    return out


def detect_cap_eff_flips(prev: dict, sigs: dict, skip_legs=()) -> list:
    """任一腿 cap_eff 翻轉（1.5↔1.0，均線五條件是否全對）。這種變化<b>只寫進 email
    內文的說明，不單獨觸發 email</b>——不計入 detect_changes 的 20pp 門檻判定，也不
    影響是否寄信；只在因其他理由（20pp drift）已經要寄信時，一併附註說明。prev 無
    'cap_eff' 欄位（舊規則、或剛切換規則的次日）時視為無基準可比，不報。"""
    if not prev or "tickers" not in prev:
        return []
    out = []
    for t in ALL_TICKERS:
        if t in skip_legs:
            continue
        pt = prev["tickers"].get(t)
        if not pt or "cap_eff" not in pt:
            continue
        if sigs[t].get("rule") == NEW_RULE_TAG or pt.get("rule") == NEW_RULE_TAG:
            continue    # 新規則上限固定 1.0，舊→新的 cap_eff 變動是規則切換，不是均線翻轉
        prev_cap = pt.get("cap_eff")
        cur_cap = sigs[t]["cap_eff"]
        if prev_cap != cur_cap:
            note_txt = "均線轉為五條全對，借錢上限回到 1.5" if cur_cap > prev_cap else "均線不再五條全對，借錢上限退回 1.0"
            out.append(f"{TICKER_MARKET[t]} {t}：cap_eff {prev_cap:.1f} → {cur_cap:.1f}（{note_txt}）")
    return out


