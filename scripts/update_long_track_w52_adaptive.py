def _leg_trigger_text(t: str, d: dict, ma60_now: float | None) -> str:
    parts = []
    if d["gate"]:
        parts.append(f"跌破 W52 {d['w52']:.2f} 出場")
    else:
        parts.append(f"漲回 W52 {d['w52']:.2f} 之上進場")
    if ma60_now is not None and d.get("rule") != NEW_RULE_TAG:   # 新規則（上限 1.0）不看均線層
        if d["ma5_on"]:
            trig_px = ma60_now * (1.0 - MA_BUF)
            parts.append(f"跌破 {trig_px:.2f}（MA60×{100*(1-MA_BUF):.0f}%）cap_eff 降回 1.0")
        else:
            parts.append(f"站回 {ma60_now:.2f}（MA60）之上（其餘四條件仍須同時成立才恢復 cap_eff 1.5）")
    return "；".join(parts)


def _desc_levels(desc: str | None) -> str | None:
    """live 顯示：state.json 的 last_change_desc 是 2026-10-31 前寫入的組合 pp 舊格式
    （「最終權重 60% → 50%」），顯示時換成水位（×2）；state 本身不改。已是水位格式的字串原樣返回。"""
    import re as _re
    if not desc:
        return desc
    desc = _re.sub(r"最終權重 (\d+)% → (\d+)%",
                   lambda m: f"水位 {int(m.group(1)) * 2}% → {int(m.group(2)) * 2}%", desc)
    desc = _re.sub(r"最終權重 → (\d+)%", lambda m: f"水位 → {int(m.group(1)) * 2}%", desc)
    desc = _re.sub(r"不借錢版單腿上限 (\d+)%", lambda m: f"不借錢版單檔上限水位 {int(m.group(1)) * 2}%", desc)
    return desc


