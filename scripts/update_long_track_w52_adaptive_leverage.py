    s = sleeve_state(px)
    fill = (1 if g["gate"] else 0) * s["sleeve"]        # 0..1 fill of the 0.5 slot
    final = WEIGHTS[t] * fill
    return {**g, **s, "sigma_base": SIGMA_BASE[t], "fill": fill, "final": final}


